// ServiceTemplate is a ready-made blocking recipe: one hook:<ID> toggles a
// forward drop rule over an FQDN address-list, scoped to the kids-devices
// src-address-list (kept in sync from kid-control by remote-hook.rsc).
// No dns/static entries: NXDOMAIN cannot be scoped by source (it would hit
// the whole LAN) and it poisons the router's own FQDN address-list
// resolution, draining the firewall layer.
type ServiceTemplate struct {
	ID      string   `json:"id"`    // param name / hook tag
	Title   string   `json:"title"` // param description
	Group   string   `json:"group"`
	Domains []string `json:"domains"`          // FQDNs: dns/static NXDOMAIN + address-list entries
	Ranges  []string `json:"ranges,omitempty"` // static CIDRs (game server networks etc.)
}

